"""ToolAdapter — generate an adapted tool from a RepoProfile / AdapterSpec.

The adapter rewrites the pipeline wiring so the tool fits the target repo:
- Sampling strategy (full / random / stratified / reservoir / window)
- Extra arguments (discount_column, lm_count_column, date_column, custom)
- Connector overrides
- Fact planner overrides
- LLM prompt overrides
"""

from __future__ import annotations

import json
import textwrap
from pathlib import Path
from typing import Any

from repo_adapter.models import AdapterSpec, RepoProfile


class ToolAdapter:
    """Generate adapted tool code from a profile/spec."""

    def __init__(self, spec: AdapterSpec) -> None:
        self.spec = spec

    @classmethod
    def from_profile(cls, profile: RepoProfile, tool_name: str = "create_markdown_summary", target_module: str = "adapted_tool") -> ToolAdapter:
        spec = AdapterSpec(
            profile=profile,
            tool_name=tool_name,
            target_module=target_module,
            sampling=profile.sampling,
            extra_arguments=profile.extra_arguments,
        )
        return cls(spec)

    def generate_tool_code(self) -> str:
        """Return Python source for the adapted DeepAgent tool."""
        spec = self.spec
        extra_params = ""
        extra_invoke = ""
        sampling_block = self._sampling_code()
        fact_block = self._fact_code()

        for arg in spec.extra_arguments:
            default_repr = repr(arg.default)
            extra_params += f', {arg.name}: str | None = {default_repr}'
            extra_invoke += f"\n    # extra arg: {arg.name} — {arg.description}"

        # Build options passthrough
        options_extra = ", ".join(f'"{a.name}": {a.name}' for a in spec.extra_arguments if a.name)

        _repo_path_esc = spec.profile.repo_path.replace(chr(92), "/")
        header = f'"""Adapted tool — auto-generated by repo_adapter.ToolAdapter.\n\nRepo: {spec.profile.repo_name} ({_repo_path_esc})\nSampling: {spec.sampling.strategy} — {spec.sampling.description}\nExtra args: {", ".join(a.name for a in spec.extra_arguments) or "none"}\nSource tool: {spec.tool_name}\nDo not edit by hand — re-run ToolAdapter to regenerate.\n"""'
        _body = textwrap.dedent(f'''from __future__ import annotations

import json
from typing import Any

try:
    from langchain_core.tools import tool as _lc_tool
    tool = _lc_tool
except ImportError:
    from pydantic import BaseModel, Field, create_model
    def tool(func=None, **_kwargs):
        def _wrap(fn):
            import inspect
            sig = inspect.signature(fn)
            fields: dict[str, Any] = {{}}
            for name, param in sig.parameters.items():
                ann = param.annotation if param.annotation is not inspect.Parameter.empty else str
                if param.default is inspect.Parameter.empty:
                    fields[name] = (ann, Field(description=name))
                else:
                    fields[name] = (ann, Field(default=param.default, description=name))
            try:
                args_model = create_model(f"{{fn.__name__}}Args", **fields)
            except Exception:
                class _Args(BaseModel): pass
                args_model = _Args
            fn.name = fn.__name__
            fn.description = (fn.__doc__ or "").strip()
            fn.args_schema = args_model
            def _invoke(args: dict[str, Any]) -> Any:
                return fn(**args)
            fn.invoke = _invoke
            return fn
        if func is None:
            return _wrap
        return _wrap(func)

# -- sampling helper (injected) --
{sampling_block}

# -- fact overrides (injected) --
{fact_block}

@tool
def {spec.tool_name}(datasets_json: str, question: str, options_json: str = "{{}}" {extra_params}) -> str:
    """Create a verified markdown summary — adapted for {spec.profile.repo_name}.

    Args:
        datasets_json: JSON array of DataRef (kind, name, data/url).
        question: Natural-language question for the summary.
        options_json: JSON object of SummaryOptions.
{self._extra_args_doc()}
    Returns:
        JSON string with markdown, facts, warnings, meta.
    """
    try:
        datasets = json.loads(datasets_json) if datasets_json else []
        if isinstance(datasets, str):
            datasets = json.loads(datasets)
        if not isinstance(datasets, list):
            raise ValueError("datasets_json must be a JSON array")

        options: dict[str, Any] = {{}}
        if options_json and options_json.strip():
            parsed = json.loads(options_json)
            if isinstance(parsed, dict):
                options = parsed

        if not question or not question.strip():
            raise ValueError("question must be non-empty")

        # Inject extra args into options so pipeline can use them
        extra = {{{options_extra}}}
        for k, v in extra.items():
            if v is not None:
                options[k] = v
        {extra_invoke}

        # Apply sampling strategy before pipeline
        datasets = _apply_sampling(datasets, options)

        # Apply fact overrides
        if _fact_overrides:
            options["_fact_overrides"] = _fact_overrides

        request: dict[str, Any] = {{"datasets": datasets, "question": question, "options": options}}

        from markdown_summary_tool.engine.pipeline import run
        try:
            from markdown_summary_tool.llm.client import get_llm_client
            llm = get_llm_client()
        except ImportError:
            llm = None

        result = run(request, llm=llm)
        return json.dumps(result, ensure_ascii=False, default=str)

    except Exception as exc:
        return json.dumps(
            {{"error_code": "summarization_failed", "message": str(exc), "details": {{"exception": type(exc).__name__}}}},
            ensure_ascii=False,
        )
''')
        code = header + "\n" + _body
        return code

    def generate_pipeline_patch(self) -> str:
        """Return a Python snippet to patch the pipeline for this repo."""
        return textwrap.dedent(f'''\
            # Pipeline patch for {self.spec.profile.repo_name}
            # Sampling: {self.spec.sampling.strategy}
            # Apply in your pipeline.py or via monkey-patch:
            from repo_adapter.sampling import apply_sampling
            from repo_adapter.models import SamplingConfig
            SAMPLING = SamplingConfig(strategy="{self.spec.sampling.strategy}", sample_size={self.spec.sampling.sample_size!r})
            # In pipeline: rows = apply_sampling(rows, SAMPLING)
            ''')

    def write(self, output_dir: str | Path) -> Path:
        """Write adapted tool to output_dir/<target_module>.py and return path."""
        out = Path(output_dir)
        out.mkdir(parents=True, exist_ok=True)
        path = out / f"{self.spec.target_module}.py"
        path.write_text(self.generate_tool_code(), encoding="utf-8")
        return path

    def to_dict(self) -> dict[str, Any]:
        return self.spec.model_dump(mode="json")

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.to_dict(), indent=indent, ensure_ascii=False, default=str)

    # -- internal helpers --

    def _sampling_code(self) -> str:
        s = self.spec.sampling
        overrides = json.dumps([o for o in self.spec.fact_overrides], indent=2) if self.spec.fact_overrides else "[]"
        return textwrap.dedent(f'''\
            _sampling_strategy = "{s.strategy}"
            _sampling_size = {s.sample_size!r}
            _sampling_seed = {s.seed!r}
            _stratify_by = {s.stratify_by!r}
            _window_size = {s.window_size!r}
            _fact_overrides = {overrides}

            def _apply_sampling(datasets: list[dict[str, Any]], options: dict[str, Any]) -> list[dict[str, Any]]:
                """Apply repo-specific sampling to datasets before pipeline."""
                from repo_adapter.sampling import apply_sampling as _do_sample
                from repo_adapter.models import SamplingConfig
                cfg = SamplingConfig(
                    strategy=options.get("sampling_strategy", _sampling_strategy),
                    sample_size=options.get("sample_size", _sampling_size),
                    stratify_by=options.get("stratify_by", _stratify_by),
                    window_size=options.get("window_size", _window_size),
                    seed=options.get("seed", _sampling_seed),
                )
                if cfg.strategy == "full" or cfg.sample_size is None:
                    return datasets
                out: list[dict[str, Any]] = []
                for ds in datasets:
                    data = ds.get("data")
                    if isinstance(data, list) and len(data) > (cfg.sample_size or 0):
                        sampled = _do_sample(data, cfg)
                        out.append({{**ds, "data": sampled}})
                    else:
                        out.append(ds)
                return datasets if not out else out
            ''').strip()

    def _fact_code(self) -> str:
        if not self.spec.fact_overrides:
            return "_fact_overrides: list[dict[str, Any]] = []"
        return f"_fact_overrides = {json.dumps(self.spec.fact_overrides, indent=2)}"

    def _extra_args_doc(self) -> str:
        if not self.spec.extra_arguments:
            return ""
        lines = []
        for a in self.spec.extra_arguments:
            lines.append(f"        {a.name}: {a.description} (default: {a.default!r})")
        return "\n".join(lines)
